def run(company,label,args,source):
    out=subprocess.run(['python3',str(TOOL),*map(str,args)],capture_output=True,text=True,check=True).stdout
    OUT.setdefault(company,[]).append({'label':label,'source':source,'args':args,'output':out})
    return out
def calc(company,label,expr,source):
    out=run(company,label,['calc','--expr',expr],source)
    return float(re.search(r'精確值:\s*([^\n]+)',out).group(1).replace(',',''))
